/**
 * WebSearch Skill
 * 提供 web_search（网页搜索）和 web_fetch（网页抓取）AI 工具
 * 搜索使用东方财富财经新闻库（按时间倒序返回最新新闻，带发布时间和来源）
 */
import { invoke } from "@tauri-apps/api/core";

export default {
  name: "web-search",
  description: "联网搜索与网页抓取能力",

  tools: [
    {
      type: "function",
      function: {
        name: "web_search",
        description:
          "搜索财经新闻获取最新信息（东方财富新闻库，按时间倒序返回，每条带发布时间）。" +
          "关键词请用 2-5 个实词（如「贵州茅台 新闻」「AI芯片 政策 2026」），不要用完整问句。" +
          "搜不到结果时先判断：关键词是否太冷门/太长？换个更通用的说法试试，" +
          "最多搜 2 次，搜不到就直接说「未找到相关信息」。",
        parameters: {
          type: "object",
          properties: {
            query: {
              type: "string",
              description: "搜索关键词，如「宁德时代 最新消息」「央行降息 2026」「贵州茅台 公告」",
            },
            max_results: {
              type: "number",
              description: "期望返回的结果数量，默认 10，最大 15",
            },
          },
          required: ["query"],
        },
      },
    },
    {
      type: "function",
      function: {
        name: "web_fetch",
        description:
          "获取指定网页的纯文本内容。当 web_search 返回了感兴趣的链接，或用已知 URL 需要读取具体内容时使用。" +
          "适用于读取财经新闻全文、公司公告详情、研究报告等。",
        parameters: {
          type: "object",
          properties: {
            url: {
              type: "string",
              description: "要抓取的网页完整 URL，如 https://example.com/article/123",
            },
          },
          required: ["url"],
        },
      },
    },
  ],

  toolImpl: {
    async web_search({ query, max_results }) {
      try {
        const results = await invoke("web_search", {
          query,
          maxResults: max_results || 10,
        });
        if (!results || results.length === 0) {
          return "[空结果] 未找到结果。可能原因：关键词太冷门/太长/太具体。请用 2-3 个通用关键词重试一次，还不行就放弃搜索。";
        }
        // 格式化为 Markdown 列表方便 AI 理解（带发布时间，最新优先）
        const formatted = results.map((r, i) => {
          const date = r.date ? ` （${r.date}）` : "";
          const source = r.url ? `\n   来源：${r.url}` : "";
          return `${i + 1}. **${r.title}**${date}\n   ${r.snippet}${source}`;
        }).join("\n\n");
        return `## 搜索结果（共 ${results.length} 条，按时间倒序）\n\n${formatted}`;
      } catch (e) {
        return `[搜索失败] ${e}`;
      }
    },

    async web_fetch({ url }) {
      try {
        const text = await invoke("web_fetch", { url });
        if (!text || text.trim().length === 0) {
          return "[抓取失败] 该网页内容为空或无法解析。可以尝试抓取搜索结果中的其他链接。";
        }
        // 限制返回长度，避免 token 消耗过大
        const maxLen = 15000;
        const truncated = text.length > maxLen
          ? text.slice(0, maxLen) + "\n\n...（内容过长，已截断）"
          : text;
        return truncated;
      } catch (e) {
        return `[抓取失败] ${e}。遇到反爬或动态加载页面时，请直接尝试搜索结果中的其他链接（优先新闻门户），不要反复重试同一个 URL。`;
      }
    },
  },

  systemPrompt: `## 联网搜索能力

你具备联网搜索和网页抓取能力。**使用前请先判断是否真的需要搜索**，避免无意义请求浪费资源。

### 判断是否需要搜索
**需要搜索的情况：**
- 用户明确要求搜索、查询最新资讯
- 问题涉及你的知识截止日期之后的实时事件（新闻、政策、公告、股价异动原因）
- 用户问「最近」「今天」「本周」等时间敏感问题
- 需要核实当前最新数据（如最新财报、最新政策）

**不需要搜索的情况：**
- 仅需股票行情/K线/资金流向 → 用本地工具（get_stock_quote、get_stock_kline 等）
- 一般投资知识、概念解释、技术分析原理
- 对话寒暄、功能咨询、帮你操作（如「帮我分析这支股票」→ 直接用本地数据）
- 你能凭训练知识自信回答的通用问题

### 搜索关键词策略（重要！）
- **用 2-5 个实词**，不要用完整问句。正确：「贵州茅台 2026 财报」，错误：「贵州茅台2026年的财报数据怎么样」
- **搜不到就换说法**：把冷门术语换成通用词（如「智算中心」→「算力 政策」），把长尾词精简
- **最多搜 2 次**：第一次没结果 → 换一组关键词 → 还没有 → 直接说「未找到相关信息」，不要死磕

### 生成搜索词（用户说"帮我搜/查 XXX"或"生成搜索词"时）
**不要反问用户要关键词，自己直接生成并搜索**，按以下步骤：
1. **拆分角度**：一次搜索只有一个主题。把需求拆成 2-3 组搜索词分别搜索，例如用户要「宁德时代的权威信息」→ 搜索「宁德时代 2026 年报」「宁德时代 最新公告」「宁德时代 机构研报 2026」
2. **组词公式**：核心实体 + 限定维度（年报/公告/财报/政策/研报/海外/产能）+ 年份
3. **搜索后向用户说明**：我生成了哪些搜索词、为什么这样拆，例如「我分三组搜索：年报、公告、研报，分别从官方披露和机构视角查」
4. 用户只是说「帮我生成搜索词」时，**先生成 2-3 组搜索词展示给用户，等用户确认/选择后再搜索**（除非用户同时要求直接搜索）

### 权威来源（用户要求"权威/官方/可靠"时）
搜索数据源是东方财富财经新闻库，结果已按时间倒序（最新优先）并带来源媒体。
- 搜索结果中优先采用**官方媒体/官方机构**发布的条目：证券时报、中国证券报、上海证券报、人民财讯、巨潮资讯（cninfo.com.cn）、交易所、公司官网
- 需要**公司公告/定期报告**时，在关键词里加「公告」「年报」「回购」等词（如「宁德时代 公告」），或直接用 web_fetch 抓巨潮资讯公告页
- 不要用 site: 语法（新闻库不识别该操作符，搜不到），直接写关键词即可
- 用户只要求"权威来源"但没指定具体来源时，优先引用官方媒体条目并标注媒体名

### 抓取策略
- **按需抓取**：只有搜索结果摘要不够时才用 web_fetch 深入阅读
- **优先抓新闻门户**：东方财富、腾讯新闻、新浪财经、同花顺、证券时报、中国证券报等静态页面最容易抓取成功（搜索结果里的大部分链接都是这类）
- **避开抓不到内容的链接**：知乎、百度百科、豆瓣、微信公众号文章等已被系统自动过滤，若用户直接给了这类链接，抓取失败是正常的，不要反复重试，直接说明即可
- **抓取失败就换链接**：遇到 403/反爬/动态加载（提示"动态加载或需要登录"）时，不要死磕同一个 URL，换搜索结果中的其他链接
- **标注来源**：回答中引用网络信息时标注来源媒体和 URL；信息注明「仅供参考」`,
};
